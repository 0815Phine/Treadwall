function Treadwall_predictable
%

global BpodSystem

%% ---------- IPC setup ---------------------------------------------------
ipc_dir = gui_ipc_dir();
gui_session_init(ipc_dir);

%% ---------- Define task parameters --------------------------------------
start_path = BpodSystem.Path.DataFolder; % folder selected in GUI;

% initialize parameters
S = struct();

% load correct parameters for location
location = questdlg('Where do you perform your experiments?',...
    'Locations',...
    'BN','ISR','ISR');
params_file = fullfile([BpodSystem.Path.ProtocolFolder '\treadwall_scrambled_parameters_', location, '.m']);
run(params_file)
fprintf('Parameters loaded for: %s \n', location);

% ------ GUI parameters
S.GUI.SubjectID = BpodSystem.GUIData.SubjectName;
S.GUI.SessionID = BpodSystem.GUIData.SessionID;
S.GUI.ITIDur = ITIDur; %in seconds
S.GUI.ScalingFactor = 1;
S.GUI.EmergencyStop = 'SendBpodSoftCode(2)';
S.GUIMeta.EmergencyStop.Style = 'pushbutton';

session_dir = ([start_path '\' S.GUI.SubjectID '\' S.GUI.SessionID]);
animal_dir = ([start_path '\' S.GUI.SubjectID]);

BpodParameterGUI('init', S);
BpodSystem.ProtocolSettings = S;
try close(BpodSystem.ProtocolFigures.ParameterGUI); catch, end

% Publish the protocol-loaded parameters so the GUI shows them as its initial
% spinbox values (predictable exposes ITIDur + ScalingFactor, no stimDur).
gui_publish_loaded_params(ipc_dir, S);

%% ---------- Trials ------------------------------------------------------
% get base name
if isfield(BpodSystem.GUIData, 'DatetimeStr') && ~isempty(BpodSystem.GUIData.DatetimeStr)
    % Use datetime from the GUI if available, so all file names match
    datetime_str = BpodSystem.GUIData.DatetimeStr;
else
    datetime_str = datestr(now, 'yyyymmdd_HHMM');
end
base_name = sprintf('%s_%s', S.GUI.SubjectID, datetime_str);

% load zones
if exist(fullfile([animal_dir base_name '_zones.csv']), 'file')
    zones_dir = fullfile([animal_dir base_name '_zones.csv']);
    fprintf('Zones have been loaded from %s\n', zones_dir);
else
    zones_dir = create_zones(animal_dir);
end

zones = readtable(zones_dir);
zones = zones.type;

stimOutput = cell(1,length(zones));
for i = 1:length(zones)
    stimOutput{i} = GetStimOutput(zones{i});
end

% one trial will be defined as one lap on the treadmill
% maximum 100 laps per session
S.GUI.MaxTrialNumber = 100;

%% ---------- Arduino Synchronizer ----------------------------------------
COM = 'COM9';
try
    arduino = serialport(COM, 115385);
catch
    error('The Arduino is not connected to %s, select the correct COM!', COM)
end

% Send initial scaling value to Arduino
scalingValue = S.GUI.ScalingFactor;
writeline(arduino, strcat(num2str(scalingValue), '\n'));
lastScalingFactor = scalingValue;

%% ---------- Rotary Encoder Module ---------------------------------------
try
    R = RotaryEncoderModule(BpodSystem.ModuleUSB.RotaryEncoder1);
catch
    error(['The Rotary Encoder Module is not coupled to the correct COM, ' ...
        'check the Bpod Console!'])
end

R.thresholds = [-5,5];
R.sendThresholdEvents = 'On';
R.enableThresholds([1,1])

%R.startUSBStream() -> moved to after restarting timer for proper alignment
%R.streamUI() % for live streaming position, good for troubleshooting

%% ---------- Analog Output Module ----------------------------------------
try
    W = BpodWavePlayer(BpodSystem.ModuleUSB.WavePlayer1);
catch
    error(['The Analog Output Module is not coupled to the correct COM, ' ...
        'check the Bpod Console!'])
end

W.SamplingRate = 100;%in kHz
W.OutputRange = '0V:5V';
W.TriggerMode = 'Master';

% Waveforms for distances
lengthWave = 1800*W.SamplingRate; %maximum length of session
for i = 1:length(waveforms)
    W.loadWaveform(i, waveforms{i}*ones(1,lengthWave));
end

%% ---------- Analog Input Module ----------------------------------------
try
    A = BpodAnalogIn(BpodSystem.ModuleUSB.AnalogIn1);
catch
    error(['The Analog Input Module is not coupled to the correct COM, ' ...
        'check the Bpod Console!'])
end

A.SamplingRate = 100;%in kHz
A.nActiveChannels = 3;
A.InputRange = {'0V:10V', '0V:10V', '0V:10V', '0V:10V', '0V:10V', '0V:10V', '0V:10V', '0V:10V'};
A.Thresholds(1,1:3) = [4.0, 2.5, 1.5];
A.ResetVoltages(1,1:3) = [3.2, 1.65, 1.65]; % TO DO: check reset voltage for first trigger
A.SMeventsEnabled(1,1:3) = [1, 1, 1];
A.startReportingEvents()

%A.scope() % for live streaming inputs, good for troubleshooting

%% ---------- Restart Timer -----------------------------------------------
% Discard any stale bytes left in the Bpod serial buffer (e.g. after an
% emergency stop) so the clock-reset confirmation byte is read correctly.
nStale = BpodSystem.SerialPort.bytesAvailable;
if nStale > 0, BpodSystem.SerialPort.read(nStale, 'uint8'); end
BpodSystem.SerialPort.write('*', 'uint8');
Confirmed = BpodSystem.SerialPort.read(1,'uint8');
if Confirmed ~= 1
    error('Faulty clock reset')
end

% start rotary encoder stream
R.startUSBStream()

