            'OutputActions', {'WavePlayer1', stimOutput{2}});
        sma = AddState(sma, 'Name', 'z2bb',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z1b', 'AnalogIn1_2', 'z2fb', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{2}});

        % zone 3
        sma = AddState(sma, 'Name', 'z3f',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z4f', 'AnalogIn1_3', 'z3b', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{3}});
        sma = AddState(sma, 'Name', 'z3b',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z2b', 'AnalogIn1_2', 'z3f', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{3}});
        sma = AddState(sma, 'Name', 'z3fb',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z4fb', 'AnalogIn1_3', 'z3bb', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{3}});
        sma = AddState(sma, 'Name', 'z3bb',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z2bb', 'AnalogIn1_2', 'z3fb', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{3}});

        % zone 4: exit trial after completing zone 4
        sma = AddState(sma, 'Name', 'z4f',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','exit', 'AnalogIn1_3', 'z4b', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{4}});
        sma = AddState(sma, 'Name', 'z4b',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z3b', 'AnalogIn1_2', 'z4f', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{4}});
        sma = AddState(sma, 'Name', 'z4fb',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z1f', 'AnalogIn1_3', 'z4bb', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{4}});
        sma = AddState(sma, 'Name', 'z4bb',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z3bb', 'AnalogIn1_2', 'z4fb', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{4}});

        % reached timer
        sma = AddState(sma, 'Name', 'EndBuffer',...
            'Timer', 10,...
            'StateChangeConditions', {'Tup', 'StopCamera', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', ['!' 3 0 0]});

        sma = AddState(sma, 'Name', 'StopCamera', ...
            'Timer', 1,...
            'StateChangeConditions', {'Tup', 'exit'},...
            'OutputActions', {'BNC1',1});

    % last trial: with end buffer
    elseif currentTrial == S.GUI.MaxTrialNumber
        % zone 1
        sma = AddState(sma, 'Name', 'z1f',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z2f', 'AnalogIn1_3', 'z1b', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{1}});
        sma = AddState(sma, 'Name', 'z1b',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z4bb', 'AnalogIn1_2', 'z1f', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{1}});

        % zone 2
        sma = AddState(sma, 'Name', 'z2f',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z3f', 'AnalogIn1_3', 'z2b', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{2}});
        sma = AddState(sma, 'Name', 'z2b',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z1b', 'AnalogIn1_2', 'z2f', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{2}});
        sma = AddState(sma, 'Name', 'z2fb',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z3fb', 'AnalogIn1_3', 'z2bb', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{2}});
        sma = AddState(sma, 'Name', 'z2bb',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z1b', 'AnalogIn1_2', 'z2fb', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{2}});

        % zone 3
        sma = AddState(sma, 'Name', 'z3f',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z4f', 'AnalogIn1_3', 'z3b', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{3}});
        sma = AddState(sma, 'Name', 'z3b',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z2b', 'AnalogIn1_2', 'z3f', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{3}});
        sma = AddState(sma, 'Name', 'z3fb',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z4fb', 'AnalogIn1_3', 'z3bb', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{3}});
        sma = AddState(sma, 'Name', 'z3bb',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z2bb', 'AnalogIn1_2', 'z3fb', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{3}});

        % zone 4: exit experiment after completing zone 4
        sma = AddState(sma, 'Name', 'z4f',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','EndBuffer', 'AnalogIn1_3', 'z4b', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{4}});
        sma = AddState(sma, 'Name', 'z4b',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z3b', 'AnalogIn1_2', 'z4f', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{4}});
        sma = AddState(sma, 'Name', 'z4fb',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z1f', 'AnalogIn1_3', 'z4bb', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{4}});
        sma = AddState(sma, 'Name', 'z4bb',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z3bb', 'AnalogIn1_2', 'z4fb', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{4}});

        % exit experiment
        sma = AddState(sma, 'Name', 'EndBuffer',...
            'Timer', 10,...
            'StateChangeConditions', {'Tup', 'StopCamera', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', ['!' 3 0 0]});

        sma = AddState(sma, 'Name', 'StopCamera', ...
            'Timer', 1,...
            'StateChangeConditions', {'Tup', 'exit'},...
            'OutputActions', {'BNC1',1});

    else
        % zone 1
        sma = AddState(sma, 'Name', 'z1f',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z2f', 'AnalogIn1_3', 'z1b', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{1}});
        sma = AddState(sma, 'Name', 'z1b',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z4bb', 'AnalogIn1_2', 'z1f', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{1}});

        % zone 2
        sma = AddState(sma, 'Name', 'z2f',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z3f', 'AnalogIn1_3', 'z2b', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{2}});
        sma = AddState(sma, 'Name', 'z2b',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z1b', 'AnalogIn1_2', 'z2f', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{2}});
        sma = AddState(sma, 'Name', 'z2fb',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z3fb', 'AnalogIn1_3', 'z2bb', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{2}});
        sma = AddState(sma, 'Name', 'z2bb',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z1b', 'AnalogIn1_2', 'z2fb', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{2}});

        % zone 3
        sma = AddState(sma, 'Name', 'z3f',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z4f', 'AnalogIn1_3', 'z3b', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{3}});
        sma = AddState(sma, 'Name', 'z3b',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z2b', 'AnalogIn1_2', 'z3f', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{3}});
        sma = AddState(sma, 'Name', 'z3fb',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z4fb', 'AnalogIn1_3', 'z3bb', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{3}});
        sma = AddState(sma, 'Name', 'z3bb',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z2bb', 'AnalogIn1_2', 'z3fb', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{3}});

        % zone 4: exit trial after completing zone 4
        sma = AddState(sma, 'Name', 'z4f',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','exit', 'AnalogIn1_3', 'z4b', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{4}});
        sma = AddState(sma, 'Name', 'z4b',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z3b', 'AnalogIn1_2', 'z4f', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{4}});
        sma = AddState(sma, 'Name', 'z4fb',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z1f', 'AnalogIn1_3', 'z4bb', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{4}});
        sma = AddState(sma, 'Name', 'z4bb',...
            'Timer',0,...
            'StateChangeConditions', {'AnalogIn1_1','z3bb', 'AnalogIn1_2', 'z4fb', 'SoftCode1', 'EndBuffer', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', stimOutput{4}});

        % reached timer
        sma = AddState(sma, 'Name', 'EndBuffer',...
            'Timer', 10,...
            'StateChangeConditions', {'Tup', 'StopCamera', 'SoftCode2', 'StopCamera'},...
            'OutputActions', {'WavePlayer1', ['!' 3 0 0]});

        sma = AddState(sma, 'Name', 'StopCamera', ...
            'Timer', 1,...
            'StateChangeConditions', {'Tup', 'exit'},...
            'OutputActions', {'BNC1',1});
    end

    % run state machine
    SendStateMachine(sma);
    RawEvents = RunStateMachine;

    if ~isempty(fieldnames(RawEvents)) % If trial data was returned
        BpodSystem.Data = AddTrialEvents(BpodSystem.Data,RawEvents); % Computes trial events from raw data
        BpodSystem.Data.TrialSettings(currentTrial) = S;
        BpodSystem.Data.Loop(currentTrial) = currentTrial;
        SaveBpodSessionData; % Saves the field BpodSystem.Data to the current data file
        %SaveBpodProtocolSettings;
    end

    if strcmp(tpredict.Running, 'off')
        % timer is over
        fprintf('timer stopped\n')
        W.setFixedVoltage([1 2], 0)
        delete(tpredict)
        break

    elseif BpodSystem.Status.BeingUsed == 0
        % emergency stop
        disp('Session stopped (emergency stop or Bpod Console). Partial trial data saved.')
        W.setFixedVoltage([1 2], 0)
        stop(tpredict)
        delete(tpredict)
        break

    elseif currentTrial == S.GUI.MaxTrialNumber
        % maximum trial num reached
        W.setFixedVoltage([1 2], 0)
        stop(tpredict)
        delete(tpredict)
    end
